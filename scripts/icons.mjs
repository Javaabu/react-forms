// Generates src/adapters/html/icons.ts: the Lucide icons javaabu/forms (Blade) bundles,
// drawn by the HTML adapter. Run with `node scripts/icons.mjs` after updating lucide-react.
import { readFileSync, writeFileSync } from "node:fs"
import { URL } from "node:url"
import { createElement } from "react"
import { renderToStaticMarkup } from "react-dom/server"
import * as lucide from "lucide-react"

// The same names as javaabu/forms' resources/icons/icons.php.
const NAMES = [
  "arrow-down",
  "arrow-up",
  "arrow-up-down",
  "calendar",
  "check",
  "chevron-down",
  "chevron-left",
  "chevron-right",
  "chevron-up",
  "chevrons-up-down",
  "circle-alert",
  "circle-check",
  "circle-x",
  "clock",
  "download",
  "ellipsis",
  "external-link",
  "eye",
  "file",
  "file-text",
  "image",
  "info",
  "loader-circle",
  "map-pin",
  "pencil",
  "plus",
  "search",
  "trash-2",
  "triangle-alert",
  "upload",
  "x",
]

const pascal = (name) => name.replace(/(^|-)([a-z0-9])/g, (_, __, c) => c.toUpperCase())
const version = JSON.parse(readFileSync(new URL("../node_modules/lucide-react/package.json", import.meta.url))).version

const entries = NAMES.map((name) => {
  const component = lucide[`${pascal(name)}Icon`]
  if (!component) throw new Error(`lucide-react has no ${name}`)
  const svg = renderToStaticMarkup(createElement(component))
  const inner = svg.replace(/^<svg[^>]*>/, "").replace(/<\/svg>$/, "")
  const nodes = [...inner.matchAll(/<(\w+)([^>]*?)\/?>(?:<\/\1>)?/g)].map(([, tag, attrs]) => [
    tag,
    Object.fromEntries([...attrs.matchAll(/([\w-]+)="([^"]*)"/g)].map(([, k, v]) => [k, v])),
  ])
  return `  ${JSON.stringify(name)}: ${JSON.stringify(nodes)},`
})

writeFileSync(
  new URL("../src/adapters/html/icons.ts", import.meta.url),
  `// Lucide icons (https://lucide.dev, ISC licence), v${version}: the set javaabu/forms bundles.
// Generated by scripts/icons.mjs; don't edit by hand.

export type IconNode = [tag: string, attrs: Record<string, string>][]

export const LUCIDE_ICONS = {
${entries.join("\n")}
} satisfies Record<string, IconNode>

export type LucideIconName = keyof typeof LUCIDE_ICONS
`,
)
