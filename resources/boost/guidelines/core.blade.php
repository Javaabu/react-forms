## @javaabu/forms

- This project builds React forms with `@javaabu/forms`, the React version of the javaabu/forms Blade components: the same component names and attributes (camelCase), model binding, old input and Laravel validation errors. Don't hand-roll form fields, error lists or `_method` / `_token` inputs, and don't add react-hook-form or another form library for Laravel forms.
- Always activate the `javaabu-react-forms` skill when writing or changing a React form, a listing page or an Inertia page with fields.
